#!/usr/bin/env node
// Builds docs/traceability.md: which tests cover which use case, across Kotlin, Swift, the Firestore
// rules tests and the shared vectors. `--check` fails when an automated use case has no test or the
// committed matrix is out of date. Node 22, no dependencies.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const read = (p) => readFileSync(join(root, p), 'utf8');

const useCases = [...read('docs/use-cases.md').matchAll(/^\| (UC-\d\d) \| (.+?) \| (automated|manual) \|$/gm)]
  .map(([, id, title, mode]) => ({ id, title, mode }));

function files(dir, ext) {
  const out = [];
  for (const name of readdirSync(join(root, dir))) {
    const p = join(dir, name);
    if (name === 'node_modules' || name === 'build' || name.startsWith('.')) continue;
    if (statSync(join(root, p)).isDirectory()) out.push(...files(p, ext));
    else if (p.endsWith(ext)) out.push(p);
  }
  return out;
}

// "UC-04 to UC-07 ..." covers 04, 05, 06 and 07.
function ids(name) {
  const range = name.match(/^UC-(\d\d) to UC-(\d\d)/);
  if (range) {
    const out = [];
    for (let n = Number(range[1]); n <= Number(range[2]); n++) out.push(`UC-${String(n).padStart(2, '0')}`);
    return out;
  }
  const one = name.match(/^(UC-\d\d)/);
  return one ? [one[1]] : [];
}

const sources = {
  kotlin: { files: files('android', '.kt').filter((f) => f.includes('/src/test/')), pattern: /fun `(UC-[^`]+)`/g },
  swift: { files: files('ios', '.swift').filter((f) => f.includes('/Tests/')), pattern: /@Test\("(UC-[^"]+)"/g },
  rules: { files: files('firebase/tests', '.mjs'), pattern: /test\(['"](UC-[^'"]+)['"]/g },
};

const coverage = Object.fromEntries(useCases.map((u) => [u.id, { kotlin: [], swift: [], rules: [], vectors: 0 }]));
const unknown = [];

for (const [kind, { files: list, pattern }] of Object.entries(sources)) {
  for (const file of list) {
    for (const [, name] of read(file).matchAll(pattern)) {
      for (const id of ids(name)) {
        if (coverage[id]) coverage[id][kind].push(`${name} (${relative(root, join(root, file)).split('/').pop()})`);
        else unknown.push(`${id} in ${file}`);
      }
    }
  }
}

// The rules suite generates one shape test per rejects('...') call, all for UC-09.
for (const file of sources.rules.files) {
  for (const [, what] of read(file).matchAll(/rejects\('([^']+)'/g)) {
    coverage['UC-09'].rules.push(`UC-09 rejects ${what} (${file.split('/').pop()})`);
  }
}

// Shared vector cases run in both the Kotlin and the Swift suites.
const gatt = JSON.parse(read('spec/gatt-vectors.json'));
const reconnect = JSON.parse(read('spec/reconnect-cases.json'));
for (const c of [...gatt.heartRate, ...gatt.bloodPressure, ...gatt.documents, ...reconnect.cases]) {
  for (const id of ids(c.name)) coverage[id] ? coverage[id].vectors++ : unknown.push(`${id} in spec`);
}

const total = (c) => c.kotlin.length + c.swift.length + c.rules.length + c.vectors;
const missing = useCases.filter((u) => u.mode === 'automated' && total(coverage[u.id]) === 0).map((u) => u.id);

const lines = [
  '# Traceability matrix',
  '',
  'Generated by `node scripts/traceability.mjs --write`. Do not edit by hand.',
  '',
  '| Use case | Kotlin tests | Swift tests | Rules tests | Shared vector cases | Verified |',
  '|---|---:|---:|---:|---:|---|',
  ...useCases.map((u) => {
    const c = coverage[u.id];
    return `| ${u.id} ${u.title} | ${c.kotlin.length} | ${c.swift.length} | ${c.rules.length} | ${c.vectors} | ${u.mode} |`;
  }),
  '',
  '## Tests by use case',
  '',
  ...useCases.flatMap((u) => {
    const c = coverage[u.id];
    const all = [...c.kotlin.map((t) => `Kotlin: ${t}`), ...c.swift.map((t) => `Swift: ${t}`), ...c.rules.map((t) => `Rules: ${t}`)];
    if (c.vectors) all.push(`Shared vectors: ${c.vectors} cases, run by both the Kotlin and the Swift suites`);
    return [`### ${u.id} ${u.title}`, '', ...(all.length ? all.map((t) => `- ${t}`) : ['- Manual, see test-plan.md']), ''];
  }),
];
const matrix = lines.join('\n');

const counts = Object.values(coverage).reduce(
  (a, c) => ({ kotlin: a.kotlin + c.kotlin.length, swift: a.swift + c.swift.length, rules: a.rules + c.rules.length }),
  { kotlin: 0, swift: 0, rules: 0 },
);
console.log(`${useCases.length} use cases. Tagged tests: Kotlin ${counts.kotlin}, Swift ${counts.swift}, rules ${counts.rules}.`);

let failed = false;
if (unknown.length) { console.error(`Unknown use case ids: ${unknown.join(', ')}`); failed = true; }
if (missing.length) { console.error(`Automated use cases with no test: ${missing.join(', ')}`); failed = true; }

if (process.argv.includes('--write')) {
  writeFileSync(join(root, 'docs/traceability.md'), matrix);
  console.log('wrote docs/traceability.md');
} else if (process.argv.includes('--check')) {
  let current = '';
  try { current = read('docs/traceability.md'); } catch {}
  if (current !== matrix) { console.error('docs/traceability.md is out of date. Run node scripts/traceability.mjs --write'); failed = true; }
}
process.exit(failed ? 1 : 0);
